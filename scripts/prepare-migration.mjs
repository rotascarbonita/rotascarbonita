import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { resolve, dirname } from 'node:path';
import { randomUUID } from 'node:crypto';
import { pathToFileURL } from 'node:url';

const columns = {
  anos: ['ano','ativo','criadoEm'], escolas: ['id','nome','endereco','telefone','ativo','criadoEm'],
  turmas: ['id','ano','escolaId','nome','turno','ativo','criadoEm'],
  rotas: ['id','ano','escolaId','escolaIds','nome','motorista','veiculo','ativo','criadoEm','rotaPrincipalId'],
  pontos: ['id','rotaId','nome','ordem','horarioEstimado','ativo','criadoEm'],
  usuarios: ['id','nome','login','perfil','escolaId','exigeTroca','ativo','criadoEm'],
  estudantes: ['id','ano','escolaId','turmaId','rotaId','pontoId','nome','responsavel','celular','qrToken','ativo','criadoEm','logradouro','rotaVinculadaEm','crachaCodigo','crachaAnteriores'],
  atribuicoes: ['id','usuarioId','ano','rotaId','criadoEm'],
  chamadas: ['id','data','sentido','estudanteId','rotaId','pontoId','status','usuarioId','criadoEm','origem','escolaId'],
  dias_rota: ['id','ano','rotaId','data','encerrado','usuarioId','atualizadoEm','escolaIds'],
  motivos_ausencia: ['id','ano','rotaId','estudanteId','inicio','fim','dias','motivo','usuarioId','registradoEm'],
  auditoria: ['id','dataHora','acao','entidade','entidadeId','usuarioId','detalhes']
};
const bool = (v, fallback = true) => v === undefined || v === '' ? fallback : ![false,'false','NAO','NÃO','0',0].includes(v);
const list = v => [...new Set((Array.isArray(v) ? v : String(v || '').split(',')).map(String).map(v => v.trim()).filter(Boolean))];
const idFields = ['id','ano','escolaId','turmaId','rotaId','pontoId','usuarioId','estudanteId','rotaPrincipalId'];
function stamp(v, fallback = new Date().toISOString()) {
  if (!v) return fallback;
  // Timestamps generated by GAS are ISO. Reject ambiguous locale dates.
  if (!/^\d{4}-\d{2}-\d{2}(T|$)/.test(String(v)) || Number.isNaN(Date.parse(v))) throw Error('Data fora do formato ISO; exporte usando ExportarParaSupabase.gs.');
  return new Date(v).toISOString();
}
const day = v => {
  const value = String(v || '').slice(0, 10);
  if (!/^\d{4}-\d{2}-\d{2}$/.test(value) || Number.isNaN(Date.parse(value)) || new Date(value).toISOString().slice(0,10) !== value) throw Error('Data de chamada inválida.');
  return value;
};
const quote = v => v === null ? 'NULL' : Array.isArray(v) ? `ARRAY[${v.map(quote).join(',')}]::text[]` : typeof v === 'boolean' ? String(v) : typeof v === 'number' ? String(v) : `'${String(v).replaceAll("'", "''")}'`;
const insert = (table,row) => `insert into public.${table} (${Object.keys(row).map(c => `"${c}"`).join(',')}) values (${Object.values(row).map(quote).join(',')});`;

export function prepareMigration(input) {
  const data = input.tables || input;
  const tables = {};
  const report = { tables: {}, generatedAt: new Date().toISOString(), excluded: ['senhas antigas','salt','SESSOES','SYSTEM_SECRET'] };
  for (const [table, fields] of Object.entries(columns)) {
    tables[table] = (data[table.toUpperCase()] || data[table] || []).map(source => {
      const row = Object.fromEntries(fields.filter(f => source[f] !== undefined).map(f => [f,source[f]]));
      for (const f of idFields) if (f in row) row[f] = row[f] === '' || row[f] === null ? null : String(row[f]);
      if ('ativo' in row || fields.includes('ativo')) row.ativo = bool(row.ativo);
      for (const f of ['criadoEm','atualizadoEm','registradoEm','dataHora']) if (fields.includes(f)) row[f] = stamp(row[f]);
      if (row.rotaVinculadaEm) row.rotaVinculadaEm = stamp(row.rotaVinculadaEm); else if ('rotaVinculadaEm' in row) row.rotaVinculadaEm = null;
      for (const f of ['data','inicio','fim']) if (f in row) row[f] = day(row[f]);
      if ('encerrado' in row) row.encerrado = bool(row.encerrado,false);
      if ('escolaIds' in row) row.escolaIds = list(row.escolaIds);
      if ('crachaAnteriores' in row) row.crachaAnteriores = list(row.crachaAnteriores);
      if (table === 'usuarios') {
        row.login = String(row.login || '').trim().toLowerCase(); row.exigeTroca = true;
        if (!/^[a-z0-9][a-z0-9._-]{2,79}$/.test(row.login)) throw Error('Há login incompatível. Ajuste para 3 a 80 letras minúsculas, números, ponto, hífen ou sublinhado.');
        if (row.perfil !== 'escola') row.escolaId = null;
      }
      if (table === 'estudantes') { row.qrToken ||= randomUUID(); row.crachaCodigo ||= null; row.crachaAnteriores ||= []; }
      if (table === 'rotas') { row.escolaIds = list(row.escolaIds?.length ? row.escolaIds : row.escolaId); row.escolaId = row.escolaIds[0]; row.rotaPrincipalId ||= null; }
      if (table === 'pontos') { row.ordem = Number(row.ordem || 1); if (!Number.isInteger(row.ordem) || row.ordem < 0) throw Error('Ordem de ponto inválida.'); }
      return row;
    });
    report.tables[table] = tables[table].length;
    const ids = tables[table].map(r => table === 'anos' ? r.ano : r.id);
    if (ids.some(i => !i) || new Set(ids).size !== ids.length) throw Error(`Há IDs ausentes ou duplicados em ${table}.`);
  }
  const maps = Object.fromEntries(Object.entries(tables).map(([t,rows]) => [t,new Map(rows.map(r => [t === 'anos' ? r.ano : r.id,r]))]));
  const check = (row,field,target,required = false) => {
    if ((required && !row[field]) || (row[field] && !maps[target].has(row[field]))) throw Error(`Vínculo inválido: ${field} em ${target}. Revise a exportação completa.`);
  };
  for (const [table,rows] of Object.entries(tables)) for (const row of rows) {
    if ('ano' in row && table !== 'anos') check(row,'ano','anos',true);
    for (const [f,t] of Object.entries({escolaId:'escolas',turmaId:'turmas',rotaId:'rotas',pontoId:'pontos',estudanteId:'estudantes'})) if (row[f]) check(row,f,t);
    if (['turmas','estudantes'].includes(table)) check(row,'escolaId','escolas',true);
    if (['pontos','atribuicoes','chamadas','dias_rota','motivos_ausencia'].includes(table)) check(row,'rotaId','rotas',true);
    if (['chamadas','motivos_ausencia'].includes(table)) check(row,'estudanteId','estudantes',true);
    if (table === 'atribuicoes') check(row,'usuarioId','usuarios',true);
    if (row.usuarioId && !maps.usuarios.has(row.usuarioId)) row.usuarioId = null; // auditoria histórica do SISTEMA
    if (table === 'rotas') { check(row,'escolaId','escolas',true); for (const id of row.escolaIds) if (!maps.escolas.has(id)) throw Error('Escola da rota não consta na exportação.');
      if (row.rotaPrincipalId && (!maps.rotas.has(row.rotaPrincipalId) || maps.rotas.get(row.rotaPrincipalId).rotaPrincipalId || row.rotaPrincipalId === row.id)) throw Error('Alias de rota inválido ou encadeado.'); }
    if (table === 'chamadas') {
      row.escolaId ||= maps.rotas.get(row.rotaId)?.escolaId || maps.estudantes.get(row.estudanteId)?.escolaId;
      check(row,'escolaId','escolas',true); row.origem ||= 'MANUAL';
    }
    if (table === 'dias_rota') { row.escolaIds = row.escolaIds?.length ? row.escolaIds : list(maps.rotas.get(row.rotaId)?.escolaId); if (!row.escolaIds.length) throw Error('Dia de rota sem escola.'); }
  }
  const unique = (rows,fn,message) => { const keys = rows.map(fn); if (new Set(keys).size !== keys.length) throw Error(message); };
  unique(tables.usuarios,r => r.login,'Há logins duplicados após normalizar maiúsculas.');
  unique(tables.estudantes,r => r.qrToken,'Há tokens QR duplicados.');
  unique(tables.chamadas,r => JSON.stringify([r.data,r.sentido,r.estudanteId]),'Há chamadas duplicadas no mesmo dia/sentido; revise antes de migrar.');
  unique(tables.atribuicoes,r => JSON.stringify([r.usuarioId,r.ano,r.rotaId]),'Há atribuições duplicadas; revise antes de migrar.');
  const reserved = new Map();
  for (const s of tables.estudantes) for (const code of [s.crachaCodigo,...s.crachaAnteriores].filter(Boolean)) {
    if (!/^RC-[2-9A-HJ-NP-Z]{4}-[2-9A-HJ-NP-Z]{4}$/.test(code)) throw Error('Há um código de crachá inválido.');
    if (reserved.has(code) && reserved.get(code) !== s.id) throw Error('Um código de crachá pertence a dois estudantes.');
    reserved.set(code,s.id);
  }
  tables.rotas.sort((a,b) => Number(Boolean(a.rotaPrincipalId)) - Number(Boolean(b.rotaPrincipalId)));
  const sql = [
    '-- DADOS PRIVADOS: execute uma vez em um projeto novo. Não envie este arquivo ao GitHub.',
    'begin;', 'set standard_conforming_strings=on;',
    `do $$ begin if exists(select 1 from public.estudantes) or exists(select 1 from public.escolas) or exists(select 1 from public.usuarios) then raise exception 'Destino não está vazio. A importação foi interrompida.'; end if; end $$;`
  ];
  for (const [code,student] of reserved) sql.push(`insert into private.badge_registry(code,student_id) values(${quote(code)},${quote(student)});`);
  for (const [table,rows] of Object.entries(tables)) for (const row of rows) {
    sql.push(insert(table,row));
    if (table === 'estudantes' && !row.crachaCodigo) sql.push(`update public.estudantes set "crachaCodigo"=private.new_badge(id) where id=${quote(row.id)};`);
  }
  sql.push('update public.sync_state set revision=revision+1 where id=1;', 'commit;');
  return { sql: sql.join('\n') + '\n', report };
}
if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  try {
    const input = process.argv[2];
    if (!input) throw Error('Uso: npm run migrate:prepare -- caminho/backup.json [.private/migracao]');
    const output = resolve(process.argv[3] || '.private/migracao');
    const result = prepareMigration(JSON.parse(await readFile(input,'utf8')));
    await mkdir(output,{recursive:true,mode:0o700});
    await writeFile(resolve(output,'dados.sql'),result.sql,{mode:0o600});
    await writeFile(resolve(output,'conferencia.json'),JSON.stringify(result.report,null,2),{mode:0o600});
    console.log('Migração preparada. Confira as quantidades em .private/migracao/conferencia.json antes de executar dados.sql. Nenhuma senha antiga foi copiada.');
  } catch (error) { console.error(error.message); process.exitCode=1; }
}
